// Embeds the link-preview card's logo and fonts into a TS module.
//
// Why (8 November 2026, Cloudflare move — docs/deploy-cloudflare.md): banner.tsx
// used to readFile() these from src/lib/og/ at request time. Workers have no
// filesystem, so every opengraph-image / twitter-image route returned 500 with
// "no such file or directory, readAll '/bundle/src/lib/og/logo-stacked.png'".
// Embedding them as base64 works on Workers and on Node alike.
//
// The source files are unchanged (Rule 3: the logo is rendered, never recreated;
// fonts are the same ttf builds). Re-run after replacing any of them:
//   node scripts/embed-og-assets.mjs
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "src", "lib", "og");
const files = {
  logoStacked: "logo-stacked.png",
  bantayogExtraBold: "fonts/BantayogSans-ExtraBold.ttf",
  workSansRegular: "fonts/WorkSans-Regular.ttf",
};

let out = `// GENERATED by scripts/embed-og-assets.mjs — do not edit by hand.
// Base64 copies of the files beside this one; see the script for why.
`;
for (const [name, rel] of Object.entries(files)) {
  const b64 = (await readFile(join(dir, rel))).toString("base64");
  out += `\nexport const ${name}Base64 =\n  "${b64}";\n`;
}
await writeFile(join(dir, "assets.generated.ts"), out);
console.log("wrote src/lib/og/assets.generated.ts");
